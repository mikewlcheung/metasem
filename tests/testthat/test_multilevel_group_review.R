test_that("multiple-group summaries align named inputs and variable means", {
  set.seed(475); g <- rep(c("A","B"),c(100,300)); x <- rnorm(400)
  d <- data.frame(g=g,x=x,y=ifelse(g=="A",.2,1)*x+rnorm(400))
  parts <- split(d,d$g)
  C <- lapply(parts,function(z) cov(z[,c("x","y")]))
  M <- lapply(parts,function(z) colMeans(z[,c("x","y")]))
  N <- vapply(parts,nrow,integer(1))
  ram <- lavaan2RAM("y ~ c(b,b)*x",ngroups=2)
  raw <- sem(RAM=ram,data=d,group="g")
  reference <- sem(RAM=ram,Cov=C,means=M,numObs=N)
  swapped <- M; swapped[[1]] <- rev(swapped[[1]])
  reordered <- sem(RAM=ram,Cov=C,means=rev(swapped),numObs=rev(N))
  for (fit in list(raw,reference,reordered)) expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_equal(coef(reordered),coef(reference),tolerance=1e-6)
  expect_equal(vcov(reordered),vcov(reference),tolerance=1e-6)
  expect_equal(reordered$mx.fit$output$fit,reference$mx.fit$output$fit,tolerance=1e-8)
  expect_equal(coef(reference),coef(raw),tolerance=1e-5)
  bad <- M; names(bad) <- c("A","wrong")
  expect_error(sem(RAM=ram,Cov=C,means=bad,numObs=N,run=FALSE),"must match the group names")
  duplicate <- N; names(duplicate) <- c("A","A")
  expect_error(sem(RAM=ram,Cov=C,means=M,numObs=duplicate,run=FALSE),"complete and unique")
  expect_warning(sem(RAM=ram,Cov=unname(C),means=M,numObs=unname(N),run=FALSE),"matched by position")
})

test_that("two-level cluster summaries align names at both levels", {
  set.seed(473); id <- rep(seq_len(25),times=rep(3:7,5)); u <- rnorm(25)
  d <- data.frame(id=id,y=u[id]+rnorm(length(id)))
  parts <- split(d["y"],d$id); C <- lapply(parts,cov)
  M <- lapply(parts,colMeans); N <- vapply(parts,nrow,integer(1))
  ram <- lavaan2RAM("level: 1\ny ~~ ew*y\nlevel: 2\ny ~~ eb*y")
  raw <- sem(RAM=ram,data=d,cluster="id")
  reference <- sem(RAM=ram,Cov=C,means=M,numObs=N,cluster="id")
  reordered <- sem(RAM=ram,Cov=C,means=rev(M),numObs=rev(N),cluster="id")
  for (fit in list(raw,reference,reordered)) expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_equal(coef(reordered),coef(reference),tolerance=1e-6)
  expect_equal(vcov(reordered),vcov(reference),tolerance=1e-6)
  expect_equal(reordered$mx.fit$output$fit,reference$mx.fit$output$fit,tolerance=1e-8)
  expect_equal(coef(reference),coef(raw),tolerance=1e-5)
  expect_equal(reference$mx.fit$output$fit,raw$mx.fit$output$fit,tolerance=1e-6)
  bad <- M; names(bad)[1] <- "wrong"
  expect_error(sem(RAM=ram,Cov=C,means=bad,numObs=N,cluster="id",run=FALSE),"must match the cluster names")
  ## Named means within a cluster are also matched to covariance variables.
  S <- matrix(c(1,.2,.2,2),2,dimnames=list(c("x","y"),c("x","y")))
  out <- .expand.cluster.summaries(list(one=S),list(one=c(y=3,x=1)),c(one=5),"id")
  expect_equal(unname(colMeans(out[,c("x","y")])),c(1,3),tolerance=1e-10)
})

test_that("nested group and cluster summaries align independently", {
  set.seed(480); g <- rep(c("A","B"),each=50); id <- rep(rep(1:10,each=5),2)
  d <- data.frame(g=g,id=paste(g,id),y=rnorm(20)[match(paste(g,id),unique(paste(g,id)))]+rnorm(100))
  groups <- split(d,d$g); pieces <- lapply(groups,function(z) split(z["y"],z$id))
  C <- lapply(pieces,function(z) lapply(z,cov))
  M <- lapply(pieces,function(z) lapply(z,colMeans))
  N <- lapply(pieces,function(z) vapply(z,nrow,integer(1)))
  m <- "group: A\nlevel: 1\ny ~~ y\nlevel: 2\ny ~~ y\ngroup: B\nlevel: 1\ny ~~ y\nlevel: 2\ny ~~ y"
  ram <- lavaan2RAM(m,ngroups=2)
  raw <- sem(RAM=ram,data=d,group="g",cluster="id")
  reference <- sem(RAM=ram,Cov=C,means=M,numObs=N,group="g",cluster="id")
  reordered <- sem(RAM=ram,Cov=C,means=rev(lapply(M,rev)),numObs=rev(lapply(N,rev)),group="g",cluster="id")
  for (fit in list(raw,reference,reordered)) expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_equal(coef(reordered),coef(reference),tolerance=1e-6)
  expect_equal(reordered$mx.fit$output$fit,reference$mx.fit$output$fit,tolerance=1e-8)
  expect_equal(coef(raw),coef(reference),tolerance=1e-5)
  expect_equal(raw$mx.fit$output$fit,reference$mx.fit$output$fit,tolerance=1e-6)
})

test_that("two-level latent mean identification warning respects fixed intercepts", {
  m <- "level: 1\nfw =~ y1+y2+y3\nlevel: 2\nfb =~ y1+y2+y3\nfb ~ mb*1"
  expect_warning(lavaan2RAM(m),"between-level mean.*may be unidentified")
  identified <- paste(m,"y1 ~ 0*1",sep="\n")
  expect_no_warning(ram <- lavaan2RAM(identified))
  constrained <- paste(m,"y1 ~ i1*1","i1 == 0",sep="\n")
  expect_no_warning(lavaan2RAM(constrained))
  d <- lavaan::Demo.twolevel
  fit <- sem(RAM=ram,data=d,cluster="cluster")
  ref <- lavaan::sem(identified,data=d,cluster="cluster",std.lv=TRUE,
                     meanstructure=TRUE,information="observed")
  expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_true(lavaan::lavInspect(ref,"converged")); expect_true(lavaan::lavInspect(ref,"post.check"))
  expect_equal(fit$mx.fit$output$fit,-2*as.numeric(logLik(ref)),tolerance=1e-6)
  expect_equal(unname(coef(fit)["mb"]),unname(lavaan::coef(ref)["mb"]),tolerance=1e-4)
  expect_equal(unname(sqrt(vcov(fit)["mb","mb"])),unname(sqrt(lavaan::vcov(ref)["mb","mb"])),tolerance=1e-4)
})

test_that("two-level counts exclude uninformative observations and clusters", {
  set.seed(918); id <- rep(seq_len(30),each=4)
  d <- data.frame(id=id,y=rnorm(30)[id]+rnorm(120))
  extra <- rbind(d,data.frame(id=rep(31,4),y=NA_real_))
  ram <- lavaan2RAM("level: 1\ny ~~ ew*y\nlevel: 2\ny ~~ eb*y")
  a <- sem(RAM=ram,data=d,cluster="id"); b <- sem(RAM=ram,data=extra,cluster="id")
  expect_true(a$mx.fit$output$status$code %in% c(0,1)); expect_true(b$mx.fit$output$status$code %in% c(0,1))
  expect_equal(coef(a),coef(b),tolerance=1e-5)
  expect_equal(a$mx.fit$output$fit,b$mx.fit$output$fit,tolerance=1e-8)
  expect_equal(summary(b)$no.studies,120); expect_equal(summary(b)$no.clusters,30)
  expect_equal(summary(a)$informationCriteria,summary(b)$informationCriteria,tolerance=1e-8)
  expect_equal(vcov(a,robust=TRUE),vcov(b,robust=TRUE),tolerance=1e-5)
})

test_that("clusters observed only at between level still contribute", {
  set.seed(7); id <- rep(1:25,each=5); d <- data.frame(id=id,w=rnorm(25)[id])
  d$y <- .3*d$w+rnorm(25)[id]+rnorm(125); d$y[c(1:3,6:10)] <- NA
  m <- "level: 1\ny ~~ y\nlevel: 2\ny ~ w\nw ~~ w"
  fit <- sem(RAM=lavaan2RAM(m),data=d,cluster="id")
  ref <- suppressWarnings(lavaan::sem(m,data=d,cluster="id",fixed.x=FALSE,missing="ML"))
  expect_true(fit$mx.fit$output$status$code %in% c(0,1)); expect_true(lavaan::lavInspect(ref,"converged"))
  expect_equal(summary(fit)$no.studies,lavaan::lavInspect(ref,"nobs"))
  expect_equal(summary(fit)$no.clusters,25)
  expect_equal(fit$mx.fit$output$fit,-2*as.numeric(logLik(ref)),tolerance=1e-6)
  expect_equal(unname(summary(fit)$informationCriteria["BIC:","Parameters Penalty"]),as.numeric(BIC(ref)),tolerance=1e-6)
  reduced <- sem(RAM=lavaan2RAM(m),data=d[!is.na(d$y),],cluster="id")
  expect_gt(abs(fit$mx.fit$output$fit-reduced$mx.fit$output$fit),1)
  expect_equal(summary(reduced)$no.clusters,24)
})

test_that("combined models ignore auxiliary submodels in summary and robust covariance", {
  set.seed(21); g <- rep(c("A","B"),each=80); id <- rep(seq_len(40),each=4)
  d <- data.frame(g=g,id=id,y=rnorm(40)[id]+rnorm(length(id)))
  m <- "group: A\nlevel: 1\ny ~~ ew1*y\nlevel: 2\ny ~~ eb1*y\ngroup: B\nlevel: 1\ny ~~ ew2*y\nlevel: 2\ny ~~ eb2*y"
  ram <- lavaan2RAM(m,ngroups=2)
  reference <- sem(RAM=ram,data=d,group="g",cluster="id")
  fit <- sem(RAM=ram,data=d,group="g",cluster="id",mxModel.Args=list(OpenMx::mxModel("aux")))
  expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_equal(summary(fit)$no.clusters,40)
  expect_equal(coef(fit),coef(reference),tolerance=1e-6)
  expect_equal(vcov(fit,robust=TRUE),vcov(reference,robust=TRUE),tolerance=1e-5)
})

test_that("internal group and between model names avoid user parameter names", {
  set.seed(21); g <- rep(c("A","B"),each=80); id <- rep(seq_len(40),each=4)
  d <- data.frame(g=g,id=id,y=rnorm(40)[id]+rnorm(length(id)))
  m <- "group: A\nlevel: 1\ny ~~ group_1*y\nlevel: 2\ny ~~ eba*y\ngroup: B\nlevel: 1\ny ~~ between_group_2*y\nlevel: 2\ny ~~ ebb*y"
  ram <- lavaan2RAM(m,ngroups=2)
  fit <- sem(RAM=ram,data=d,group="g",cluster="id",mxModel.Args=list(OpenMx::mxModel("group_1_1")))
  ref.model <- gsub("group_1", "varianceA", m, fixed=TRUE)
  ref.model <- gsub("between_group_2", "varianceB", ref.model, fixed=TRUE)
  reference <- sem(RAM=lavaan2RAM(ref.model,ngroups=2),data=d,group="g",cluster="id")
  expect_null(fit$error); expect_true(fit$mx.fit$output$status$code %in% c(0,1))
  expect_false(any(unname(fit$group.map) %in% c("group_1","group_1_1")))
  expect_false(paste0("between_",unname(fit$group.map[2])) == "between_group_2")
  expect_equal(fit$mx.fit$output$fit,reference$mx.fit$output$fit,tolerance=1e-6)
  expect_equal(unname(coef(fit)["group_1"]),unname(coef(reference)["varianceA"]),tolerance=1e-5)
  expect_equal(unname(coef(fit)["between_group_2"]),unname(coef(reference)["varianceB"]),tolerance=1e-5)
})
